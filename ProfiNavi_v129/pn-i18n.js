 const KG_RU=Object.fromEntries(Object.entries(RU_KG).map(([a,b])=>[b,a]));
 function lang(){return localStorage.getItem(KEY)||'ru'}
 function translateString(v,to){
   if(!v)return v;
   const dict=to==='kg'?RU_KG:KG_RU;
   if(dict[v])return dict[v];
   // Preserve whitespace around exact phrases.
   const m=v.match(/^(\s*)(.*?)(\s*)$/s);
   if(m&&dict[m[2]])return m[1]+dict[m[2]]+m[3];
   return v;
 }
 function translateNode(root=document){
   const to=lang();
   const walker=document.createTreeWalker(root,NodeFilter.SHOW_TEXT);
   const nodes=[];while(walker.nextNode())nodes.push(walker.currentNode);
   for(const n of nodes){
     if(n.parentElement?.closest('script,style'))continue;
     n.nodeValue=translateString(n.nodeValue,to);
   }
   root.querySelectorAll?.('[placeholder],[aria-label],[title]').forEach(el=>{
     for(const a of ['placeholder','aria-label','title']){
       if(el.hasAttribute(a))el.setAttribute(a,translateString(el.getAttribute(a),to));
     }
   });
   document.documentElement.lang=to==='kg'?'ky':'ru';
   document.querySelectorAll('[data-pn-lang-toggle]').forEach(btn=>{
     btn.textContent=to==='kg'?'🇷🇺':'🇰🇬';
     btn.setAttribute('aria-label',to==='kg'?'Орусча':'Кыргызча');
     btn.title=to==='kg'?'Русский':'Кыргызча';
   });
 }
